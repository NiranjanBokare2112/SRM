"""One-off generator for supabase/migrations/20261124000000_operators.sql.

Operators are counter staff with their own login. They may bill, return, look up bills and
manage customer udhaar, but never see purchase costs, profit, purchases, suppliers or settings.
The billing functions are copied from earlier migrations with exactly one change each:
assert_owner() -> assert_staff().
"""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
mig = lambda name: (root / "supabase/migrations" / name).read_text(encoding="utf8")

def take(sql: str, signature: str) -> str:
    m = re.search(r"create or replace function public\." + re.escape(signature) + r".*?^end \$\$;", sql, re.S | re.M)
    assert m, signature
    fn = m.group(0)
    assert fn.count("perform public.assert_owner();") == 1, signature
    return fn.replace("perform public.assert_owner();", "perform public.assert_staff();")

create_sale = take(mig("20261123000000_customers_substitutes.sql"), "create_sale(p jsonb)")
create_return = take(mig("20261121000000_billing.sql"), "create_sales_return(p jsonb)")
record_payment = take(mig("20261123000000_customers_substitutes.sql"), "record_customer_payment(")

sql = """-- =====================================================================
-- Operator (counter staff) logins with limited access.
-- Generated by scripts/build-migration-4.py.
--
-- Owners: everything.  Operators: billing, returns, bill lookup, customers & udhaar.
-- Operators read sales/batches through *_public views that leave out purchase cost
-- and profit; the base tables stay owner-only.
-- =====================================================================

create table public.operators (
  user_id uuid primary key references auth.users(id) on delete cascade,
  name text not null check (length(trim(name)) > 0),
  created_at timestamptz not null default now()
);
alter table public.operators enable row level security;
create policy operators_read on public.operators for select to authenticated using (public.is_owner() or user_id = auth.uid());

create or replace function public.is_operator()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.operators where user_id = auth.uid()) $$;

create or replace function public.is_staff()
returns boolean language sql stable security definer set search_path = public
as $$ select public.is_owner() or public.is_operator() $$;

create or replace function public.my_role()
returns text language sql stable security definer set search_path = public
as $$ select case when public.is_owner() then 'owner' when public.is_operator() then 'operator' end $$;

create or replace function public.assert_staff()
returns void language plpgsql stable security definer set search_path = public
as $$
begin
  if not public.is_staff() then raise exception 'Not authorised' using errcode = '42501'; end if;
end $$;

-- What operators may read directly.
drop policy if exists products_read on public.products;
create policy products_read on public.products for select to authenticated using (public.is_staff());
drop policy if exists settings_read on public.shop_settings;
create policy settings_read on public.shop_settings for select to authenticated using (public.is_staff());
drop policy if exists staff_read on public.staff;
create policy staff_read on public.staff for select to authenticated using (public.is_staff());
drop policy if exists customers_read on public.customers;
drop policy if exists customers_insert on public.customers;
drop policy if exists customers_update on public.customers;
create policy customers_read on public.customers for select to authenticated using (public.is_staff());
create policy customers_insert on public.customers for insert to authenticated with check (public.is_staff());
create policy customers_update on public.customers for update to authenticated using (public.is_staff()) with check (public.is_staff());
drop policy if exists customer_payments_read on public.customer_payments;
create policy customer_payments_read on public.customer_payments for select to authenticated using (public.is_staff());

-- Only the owner may set or change a customer's old (opening) udhaar.
create or replace function public.guard_customer_opening_balance()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  -- Applies to operator sessions only (owners, setup scripts and the SQL editor are not restricted).
  if public.is_operator() and not public.is_owner() then
    if tg_op = 'INSERT' and new.opening_balance <> 0 then
      raise exception 'Only the owner can enter old udhaar' using errcode = 'P0001';
    elsif tg_op = 'UPDATE' and new.opening_balance is distinct from old.opening_balance then
      raise exception 'Only the owner can change old udhaar' using errcode = 'P0001';
    end if;
  end if;
  return new;
end $$;
create trigger customers_opening_balance_guard before insert or update on public.customers
for each row execute function public.guard_customer_opening_balance();

-- Cost-free views. These run with the view owner's rights (they bypass the owner-only
-- row policies) and filter on is_staff() themselves.
create view public.batches_public as
  select id, product_id, batch_no, expiry, mrp, stock_units, created_at from public.batches where public.is_staff();
create view public.sales_public as
  select id, fy, bill_no, bill_date, created_at, staff_id, staff_name, customer_id, patient_name, patient_phone, doctor_name,
         payment_mode, gross, discount_pct, discount, taxable, gst, round_off, net, returned_amount
  from public.sales where public.is_staff();
create view public.sale_items_public as
  select id, sale_id, product_id, batch_id, product_name, packing, pack_size, batch_no, expiry, mrp, gst_rate,
         units, amount, net_amount, taxable, gst, returned_units
  from public.sale_items where public.is_staff();
create view public.sales_returns_public as
  select id, fy, return_no, return_date, created_at, sale_id, refund_mode, taxable, gst, amount, note
  from public.sales_returns where public.is_staff();

-- Customer balances must see every credit bill, so it also runs with owner rights.
drop view if exists public.customer_balances;
create view public.customer_balances as
select c.id, c.name, c.phone, c.address, c.opening_balance,
  c.opening_balance
  + coalesce((select sum(s.net) from public.sales s where s.customer_id = c.id and s.payment_mode = 'credit'), 0)
  - coalesce((select sum(r.amount) from public.sales_returns r join public.sales s on s.id = r.sale_id
              where s.customer_id = c.id and r.refund_mode = 'credit'), 0)
  - coalesce((select sum(cp.amount) from public.customer_payments cp where cp.customer_id = c.id), 0) as balance,
  (select max(s.created_at) from public.sales s where s.customer_id = c.id) as last_bill_at,
  (select count(*) from public.sales s where s.customer_id = c.id)::integer as bills
from public.customers c
where public.is_staff();

revoke all on public.batches_public, public.sales_public, public.sale_items_public, public.sales_returns_public, public.customer_balances from anon;
grant select on public.batches_public, public.sales_public, public.sale_items_public, public.sales_returns_public, public.customer_balances to authenticated;

-- Operator accounts, managed by the owner from Settings.
create view public.operator_list as
  select o.user_id, o.name, u.email, o.created_at
  from public.operators o join auth.users u on u.id = o.user_id
  where public.is_owner();
revoke all on public.operator_list from anon;
grant select on public.operator_list to authenticated;

create or replace function public.create_operator(p_email text, p_password text, p_name text)
returns uuid
language plpgsql security definer set search_path = public, extensions
as $$
declare v_user uuid; v_email text := lower(trim(p_email));
begin
  perform public.assert_owner();
  if v_email !~ '^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$' then raise exception 'Enter a valid email for the operator login' using errcode = 'P0001'; end if;
  if coalesce(length(p_password), 0) < 8 then raise exception 'Password must be at least 8 characters' using errcode = 'P0001'; end if;
  if coalesce(trim(p_name), '') = '' then raise exception 'Enter the operator name' using errcode = 'P0001'; end if;

  select id into v_user from auth.users where lower(email) = v_email;
  if v_user is not null and exists (select 1 from public.owners where user_id = v_user) then
    raise exception 'This email is an owner login' using errcode = 'P0001';
  end if;
  if v_user is null then
    v_user := gen_random_uuid();
    insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
                            raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
                            confirmation_token, recovery_token, email_change_token_new, email_change)
    values ('00000000-0000-0000-0000-000000000000', v_user, 'authenticated', 'authenticated', v_email,
            extensions.crypt(p_password, extensions.gen_salt('bf')), now(),
            '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '');
    insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
    values (gen_random_uuid(), v_user, v_user::text,
            jsonb_build_object('sub', v_user::text, 'email', v_email, 'email_verified', true), 'email', now(), now(), now());
  else
    update auth.users set encrypted_password = extensions.crypt(p_password, extensions.gen_salt('bf')), updated_at = now() where id = v_user;
  end if;
  insert into public.operators (user_id, name) values (v_user, trim(p_name))
  on conflict (user_id) do update set name = excluded.name;
  return v_user;
end $$;

create or replace function public.set_operator_password(p_user_id uuid, p_password text)
returns void
language plpgsql security definer set search_path = public, extensions
as $$
begin
  perform public.assert_owner();
  if coalesce(length(p_password), 0) < 8 then raise exception 'Password must be at least 8 characters' using errcode = 'P0001'; end if;
  if not exists (select 1 from public.operators where user_id = p_user_id) then raise exception 'Operator not found' using errcode = 'P0001'; end if;
  update auth.users set encrypted_password = extensions.crypt(p_password, extensions.gen_salt('bf')), updated_at = now() where id = p_user_id;
end $$;

create or replace function public.remove_operator(p_user_id uuid)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  perform public.assert_owner();
  delete from public.operators where user_id = p_user_id;
end $$;

-- Billing functions operators may use (copied unchanged except for the staff check).
""" + create_sale + "\n\n" + create_return + "\n\n" + record_payment + """

revoke execute on function public.create_operator(text, text, text), public.set_operator_password(uuid, text),
  public.remove_operator(uuid), public.guard_customer_opening_balance() from public, anon;
grant execute on function public.is_operator(), public.is_staff(), public.my_role(),
  public.create_operator(text, text, text), public.set_operator_password(uuid, text), public.remove_operator(uuid),
  public.create_sale(jsonb), public.create_sales_return(jsonb), public.record_customer_payment(uuid, numeric, text, text, date)
  to authenticated;
revoke execute on function public.assert_staff() from public, anon, authenticated;
"""
